from app.models import Store
from tests.stores_schema_spec import COLUMN_SPECS, CONSTRAINT_NAMES, INDEX_SPECS

ROOT = Path(__file__).resolve().parents[1]


def test_store_columns_match_contract() -> None:
    table = Store.__table__
    assert tuple(table.columns.keys()) == tuple(COLUMN_SPECS)
    for name, spec in COLUMN_SPECS.items():
        column = table.c[name]
        assert column.nullable is spec.nullable
        assert (column.default is not None or column.server_default is not None) is spec.has_default

    assert isinstance(table.c.id.server_default, Identity)
    assert table.c.id.server_default.always is False
    assert isinstance(table.c.license_no.type, String) and table.c.license_no.type.length == 64
    assert isinstance(table.c.source.type, String) and table.c.source.type.length == 32
    assert isinstance(table.c.area_m2.type, Numeric)
    assert (table.c.area_m2.type.precision, table.c.area_m2.type.scale) == (12, 2)
    assert isinstance(table.c.lat.type, Numeric)
    assert (table.c.lat.type.precision, table.c.lat.type.scale) == (10, 7)
    assert isinstance(table.c.lng.type, Numeric)
    assert (table.c.lng.type.precision, table.c.lng.type.scale) == (10, 7)


def test_store_preserves_unknown_and_raw_values() -> None:
    table = Store.__table__
    for name in ("is_temporary", "category_review_flag", "is_franchise"):
        column = table.c[name]
        assert isinstance(column.type, Boolean)
        assert column.nullable
        assert column.default is None
        assert column.server_default is None
    for name in ("raw_x", "raw_y", "coord_flag", "date_flag"):
        assert isinstance(table.c[name].type, Text)
    assert isinstance(table.c.deleted_at.type, DateTime) and table.c.deleted_at.type.timezone
    assert isinstance(table.c.updated_at.type, DateTime) and table.c.updated_at.type.timezone
    assert table.c.deleted_at.server_default is None
    assert table.c.updated_at.server_default is not None
    assert isinstance(table.c.batch_id.type, PostgreSQLUUID)
    assert table.c.batch_id.type.as_uuid is True
    assert not table.foreign_keys


def test_store_geometry_constraints_and_indexes_match_contract() -> None:
    table = Store.__table__
    geometry = table.c.geom.type
    assert isinstance(geometry, Geometry)
    assert geometry.geometry_type == "POINT"
    assert geometry.srid == 4326
    assert geometry.spatial_index is False

    assert {constraint.name for constraint in table.constraints} == CONSTRAINT_NAMES
    unique = next(c for c in table.constraints if isinstance(c, UniqueConstraint))
    assert tuple(column.name for column in unique.columns) == ("source", "license_no")

    indexes = {index.name: index for index in table.indexes}
    assert set(indexes) == set(INDEX_SPECS)
    for name, (method, columns) in INDEX_SPECS.items():
        index = indexes[name]
        assert tuple(column.name for column in index.columns) == columns
        assert index.dialect_options["postgresql"].get("using") == (
            "gist" if method == "gist" else False
        )

    ddl = str(CreateTable(table).compile(dialect=postgresql.dialect()))
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "geometry(POINT,4326)" in ddl


def test_store_metadata_is_registered_without_sensitive_columns() -> None:
    assert app.models.Store is Store
    assert Store.metadata is Base.metadata
    assert Base.metadata.tables["stores"] is Store.__table__
    forbidden = {"representative_name", "phone", "raw_payload", "contact"}
    assert forbidden.isdisjoint(Store.__table__.columns.keys())
    assert all(
        type(column.type).__name__ not in {"JSON", "JSONB"} for column in Store.__table__.columns
    )


def test_alembic_env_imports_models_and_uses_base_metadata() -> None:
    tree = ast.parse((ROOT / "migrations" / "env.py").read_text(encoding="utf-8"))
    assert any(
        isinstance(node, ast.Import) and any(alias.name == "app.models" for alias in node.names)
        for node in ast.walk(tree)
    )
    assert any(
        isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "target_metadata"
            for target in node.targets
        )
        and isinstance(node.value, ast.Attribute)
        and isinstance(node.value.value, ast.Name)
        and node.value.value.id == "Base"
        and node.value.attr == "metadata"
        for node in ast.walk(tree)
    )
